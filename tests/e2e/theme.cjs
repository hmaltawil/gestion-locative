const { chromium } = require('playwright');
const OUT = require('path').join(require('os').tmpdir(), 'gl-e2e-theme');
require('fs').mkdirSync(OUT, { recursive: true });
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, colorScheme: 'dark' });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  const bg = () => page.evaluate(() => getComputedStyle(document.body).backgroundColor);
  const state = () => page.evaluate(() => ({ attr: document.documentElement.getAttribute('data-theme'), meta: document.querySelector('meta[name=theme-color]').content }));
  // Before any JS module runs: theme attribute already set by the inline script
  await page.goto('http://localhost:8080/', { waitUntil: 'commit' });
  await page.waitForFunction(() => document.readyState !== 'loading');
  console.log('first paint attr:', await page.evaluate(() => document.documentElement.getAttribute('data-theme')));
  await page.waitForSelector('.welcome');
  console.log('default on a dark iPhone:', await bg(), JSON.stringify(await state()));
  await page.screenshot({ path: OUT + '/light-home.png' });
  await page.evaluate(() => { location.hash = '#/settings'; });
  await page.waitForSelector('[data-action=theme]');
  await page.screenshot({ path: OUT + '/light-settings.png' });
  await page.click('[data-action=theme][data-theme=dark]');
  console.log('dark:', await bg(), JSON.stringify(await state()));
  await page.screenshot({ path: OUT + '/dark-settings.png' });
  await page.reload(); await page.waitForSelector('[data-action=theme]');
  console.log('dark after reload:', await bg(), 'active:', await page.textContent('[data-action=theme].active'));
  await page.click('[data-action=theme][data-theme=auto]');
  console.log('auto, iPhone dark:', await bg(), JSON.stringify(await state()));
  await page.emulateMedia({ colorScheme: 'light' });
  await page.waitForTimeout(200);
  console.log('auto, iPhone light:', await bg(), JSON.stringify(await state()));
  await page.click('[data-action=theme][data-theme=light]');
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.reload(); await page.waitForSelector('[data-action=theme]');
  console.log('light after reload on dark iPhone:', await bg());
  console.log('ERRORS:', JSON.stringify(errors));
  await browser.close();
})().catch((e) => { console.error('FAILED', e.message.split('\n')[0]); process.exit(1); });
